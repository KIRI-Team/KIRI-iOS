import SwiftUI
import UserNotifications
import FirebaseCore // firebase 연결
import FirebaseAppCheck
import KakaoSDKCommon
import KakaoSDKAuth
import GoogleSignIn

// AppDelegate 추가
class AppDelegate: NSObject, UIApplicationDelegate, UNUserNotificationCenterDelegate {
  func application(_ application: UIApplication,
                   didFinishLaunchingWithOptions launchOptions: [UIApplication.LaunchOptionsKey : Any]? = nil) -> Bool {
    #if DEBUG
    print(
      "[KIRI][AppDelegate] launch: bundle=\(Bundle.main.bundleIdentifier ?? "unknown")"
    )
    #endif
    #if DEBUG
    // App Check debug tokens are generated by Firebase at runtime. They must
    // be registered manually in Firebase Console and are never persisted here.
    AppCheck.setAppCheckProviderFactory(AppCheckDebugProviderFactory())
    #endif
    FirebaseApp.configure()
    // iOS 시스템 알림 아이콘은 앱의 AppIcon 설정을 그대로 사용합니다.
    // 알림이 앱 전경에서 표시될 때만 KIRI 전용 콘텐츠 이미지를 첨부합니다.
    // 백그라운드/잠금화면 원격 푸시는 Notification Service Extension과
    // mutable-content payload가 필요하므로 서버·배포 타깃 설정을 별도로
    // 확인해야 합니다.
    UNUserNotificationCenter.current().delegate = self
    UNUserNotificationCenter.current().requestAuthorization(
      options: [.alert, .badge, .sound]
    ) { _, _ in }
    application.registerForRemoteNotifications()
    if let appKey = Bundle.main.object(
        forInfoDictionaryKey: "KAKAO_NATIVE_APP_KEY"
    ) as? String,
       !appKey.isEmpty {
      KakaoSDK.initSDK(
        appKey: appKey,
        customScheme: "kakao\(appKey)",
        // SDK 상세 로그에는 인증 URL·헤더·응답이 포함될 수 있으므로 명시적으로 끕니다.
        loggingEnable: false
      )
    }
    return true
  }

  func application(
    _ app: UIApplication,
    open url: URL,
    options: [UIApplication.OpenURLOptionsKey : Any] = [:]
  ) -> Bool {
    if AuthController.handleOpenUrl(url: url, options: options) {
      return true
    }

    return GIDSignIn.sharedInstance.handle(url)
  }

  func userNotificationCenter(
    _ center: UNUserNotificationCenter,
    willPresent notification: UNNotification,
    withCompletionHandler completionHandler: @escaping (UNNotificationPresentationOptions) -> Void
  ) {
    completionHandler([.banner, .list, .sound, .badge])
  }
}
// 여기까지 AppDelegate

@main
struct KIRIApp: App {
    // 앱 델리게이트 등록 코드 추가
    @UIApplicationDelegateAdaptor(AppDelegate.self) var delegate

    var body: some Scene {
        WindowGroup {
            RootView() // 기존에 쓰시던 RootView 그대로 유지
        }
    }
}
